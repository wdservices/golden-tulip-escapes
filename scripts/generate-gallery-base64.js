import { readdirSync, readFileSync, statSync } from 'fs';
import { join, extname, relative } from 'path';

const galleryDir = join(process.cwd(), 'public', 'images', 'gallery');
const outputFile = join(process.cwd(), 'src', 'data', 'galleryImages.ts');

const mimeTypes = {
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
  '.JPG': 'image/jpeg',
};

function getGalleryImages(dir) {
  const results = [];
  const entries = readdirSync(dir);
  for (const entry of entries) {
    const fullPath = join(dir, entry);
    const stat = statSync(fullPath);
    if (stat.isDirectory()) {
      results.push(...getGalleryImages(fullPath));
    } else {
      const ext = extname(entry);
      if (mimeTypes[ext]) {
        const relativePath = '/' + relative(join(process.cwd(), 'public'), fullPath).replace(/\\/g, '/');
        const data = readFileSync(fullPath);
        const base64 = data.toString('base64');
        const mime = mimeTypes[ext];
        results.push({
          path: relativePath,
          dataUri: `data:${mime};base64,${base64}`,
        });
      }
    }
  }
  return results;
}

const images = getGalleryImages(galleryDir);

let output = `// AUTO-GENERATED by scripts/generate-gallery-base64.js\n`;
output += `// DO NOT EDIT MANUALLY\n\n`;

output += `export const galleryImages: Record<string, string> = {\n`;
for (const img of images) {
  output += `  "${img.path}": "${img.dataUri}",\n`;
}
output += `};\n\n`;

output += `export default galleryImages;\n`;

const { writeFileSync, mkdirSync } = await import('fs');
mkdirSync(join(process.cwd(), 'src', 'data'), { recursive: true });
writeFileSync(outputFile, output);

console.log(`Generated ${images.length} base64 images → ${outputFile}`);
const sizeMB = (Buffer.byteLength(output) / 1024 / 1024).toFixed(1);
console.log(`File size: ${sizeMB} MB`);
